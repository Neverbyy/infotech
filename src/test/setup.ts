import { enableAutoUnmount } from '@vue/test-utils'
import { afterEach } from 'vitest'

/**
 * Общая настройка для всех тестов.
 *
 * Компоненты, оставшиеся смонтированными после теста, продолжают реагировать
 * на общий (модульный) роутер и на сторы, из-за чего результат начинает
 * зависеть от порядка запуска. Размонтируем их автоматически.
 */
enableAutoUnmount(afterEach)
